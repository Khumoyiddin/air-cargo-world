function ruForm(n, forms) {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return forms[2];
  if (b > 1 && b < 5) return forms[1];
  if (b === 1) return forms[0];
  return forms[2];
}
function pickForm(n, forms) {
  if (!Array.isArray(forms)) return forms;
  if (forms.length === 3) return ruForm(n, forms);
  return n === 1 ? forms[0] : forms[forms.length - 1];
}
function t(key, params) {
  const dict = I18N[LANG] || I18N.en;
  let s = dict[key] !== undefined ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  if (Array.isArray(s)) s = pickForm(params && params.n !== undefined ? params.n : 0, s);
  if (params) {
    s = s.replace(/\{(\w+)\}/g, (m, k) => {
      const v = params[k];
      if (v === undefined || v === null) return m;
      if (typeof v === 'object' && v.__html !== undefined) return v.__html;
      return esc(String(v));
    });
  }
  return s;
}
